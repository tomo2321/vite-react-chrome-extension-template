#!/usr/bin/env tsx

/**
 * MCP Config Sync Script
 *
 * Generates each coding agent's MCP config from `mcp-servers.json`
 * (plus the optional, git-ignored `mcp-servers.local.json`).
 *
 * Usage:
 *   pnpm mcp:sync [--check] [--agents claude,cursor] [--quiet]
 *
 * Run with --help for full usage information.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { Command, InvalidArgumentError } from "commander";
import { parse as parseToml, stringify as stringifyToml } from "smol-toml";
import {
  type AgentId,
  type McpSource,
  mergeIntoExisting,
  mergeSources,
  TARGETS,
} from "./mcp/targets.ts";

const ROOT = resolve(import.meta.dirname, "..");
const SOURCE_FILE = resolve(ROOT, "mcp-servers.json");
const LOCAL_FILE = resolve(ROOT, "mcp-servers.local.json");

// ---------------------------------------------------------------------------
// File helpers
// ---------------------------------------------------------------------------

function readJson<T>(path: string): T {
  return JSON.parse(readFileSync(path, "utf8")) as T;
}

function readExisting(path: string, format: "json" | "toml") {
  if (!existsSync(path)) return {};
  const text = readFileSync(path, "utf8");
  if (!text.trim()) return {};
  return format === "toml"
    ? (parseToml(text) as Record<string, unknown>)
    : (JSON.parse(text) as Record<string, unknown>);
}

function serialize(data: Record<string, unknown>, format: "json" | "toml") {
  if (format === "toml") {
    return `# Generated by \`pnpm mcp:sync\` from mcp-servers.json — do not edit the mcp_servers tables.\n${stringifyToml(data)}\n`;
  }
  return `${JSON.stringify(data, null, 2)}\n`;
}

// ---------------------------------------------------------------------------
// CLI
// ---------------------------------------------------------------------------

function parseAgents(value: string): AgentId[] {
  const ids = value.split(",").map((s) => s.trim());
  for (const id of ids) {
    if (!(id in TARGETS)) {
      throw new InvalidArgumentError(
        `Unknown agent "${id}". Valid: ${Object.keys(TARGETS).join(", ")}`,
      );
    }
  }
  return ids as AgentId[];
}

const program = new Command()
  .name("mcp:sync")
  .description(
    "Generate agent-specific MCP configs from mcp-servers.json.\n\n" +
      `Targets: ${Object.entries(TARGETS)
        .map(([id, t]) => `${id} (${t.file})`)
        .join(", ")}`,
  )
  // lint-staged appends the staged paths; they are not needed
  .argument("[files...]", "ignored")
  .option("--check", "exit with code 1 if any generated file is out of date")
  .option(
    "-a, --agents <list>",
    "comma-separated list of agents to sync",
    parseAgents,
  )
  .option("-q, --quiet", "suppress output")
  .parse();

const opts = program.opts<{
  check?: boolean;
  agents?: AgentId[];
  quiet?: boolean;
}>();

const log = (msg: string) => {
  if (!opts.quiet) console.log(msg);
};

if (!existsSync(SOURCE_FILE)) {
  console.error(`mcp:sync: ${SOURCE_FILE} not found`);
  process.exit(1);
}

const source = mergeSources(
  readJson<McpSource>(SOURCE_FILE),
  existsSync(LOCAL_FILE) ? readJson<Partial<McpSource>>(LOCAL_FILE) : undefined,
);

const agents = opts.agents ?? (Object.keys(TARGETS) as AgentId[]);
const stale: string[] = [];

for (const id of agents) {
  const target = TARGETS[id];
  const path = resolve(ROOT, target.file);
  const current = existsSync(path) ? readFileSync(path, "utf8") : undefined;
  const next = serialize(
    mergeIntoExisting(
      readExisting(path, target.format),
      target,
      source.servers,
    ),
    target.format,
  );

  if (current === next) continue;

  if (opts.check) {
    stale.push(target.file);
    continue;
  }

  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, next);
  log(`mcp:sync: updated ${target.file}`);
}

if (opts.check && stale.length > 0) {
  console.error(
    `mcp:sync: out of date: ${stale.join(", ")}\nRun \`pnpm mcp:sync\` to regenerate.`,
  );
  process.exit(1);
}
